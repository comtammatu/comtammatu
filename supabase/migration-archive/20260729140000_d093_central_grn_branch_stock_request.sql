-- ── 9) Stock request RPCs ───────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.create_stock_request_draft(
  p_branch_id bigint,
  p_notes text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_tenant bigint := public.auth_tenant_id();
  v_kind text;
  v_id bigint;
  v_number text;
BEGIN
  IF v_uid IS NULL OR v_tenant IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '28000';
  END IF;

  SELECT branch.branch_kind INTO v_kind
  FROM public.branches AS branch
  WHERE branch.id = p_branch_id
    AND branch.tenant_id = v_tenant
    AND branch.is_active IS TRUE;

  IF v_kind IS DISTINCT FROM 'branch' THEN
    RAISE EXCEPTION 'stock_request_branch_site_only'
      USING ERRCODE = 'check_violation';
  END IF;

  IF NOT public.auth_is_owner(auth.uid())
     AND NOT public.has_permission(p_branch_id, 'inventory:request_create')
  THEN
    RAISE EXCEPTION 'forbidden_request_create' USING ERRCODE = '42501';
  END IF;

  v_number := public.next_inventory_doc_number(v_tenant, 'stock_request');

  INSERT INTO public.stock_requests (
    tenant_id, branch_id, request_number, status, notes, created_by
  )
  VALUES (
    v_tenant, p_branch_id, v_number, 'draft', p_notes, v_uid
  )
  RETURNING id INTO v_id;

  RETURN jsonb_build_object(
    'request_id', v_id,
    'request_number', v_number
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.add_stock_request_line(
  p_request_id bigint,
  p_ingredient_id bigint,
  p_entry_unit_id bigint,
  p_quantity numeric
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_tenant bigint := public.auth_tenant_id();
  v_req public.stock_requests%ROWTYPE;
  v_fulfill text;
  v_item_id bigint;
BEGIN
  IF v_uid IS NULL OR v_tenant IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '28000';
  END IF;

  SELECT * INTO v_req
  FROM public.stock_requests AS req
  WHERE req.id = p_request_id
    AND req.tenant_id = v_tenant
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'stock_request_not_found' USING ERRCODE = 'no_data_found';
  END IF;
  IF v_req.status IS DISTINCT FROM 'draft' THEN
    RAISE EXCEPTION 'stock_request_not_draft' USING ERRCODE = '22023';
  END IF;
  IF NOT public.auth_is_owner(auth.uid())
     AND NOT public.has_permission(
       v_req.branch_id,
       'inventory:request_create'
     )
  THEN
    RAISE EXCEPTION 'forbidden_request_create' USING ERRCODE = '42501';
  END IF;

  SELECT ingredient.default_fulfill_site_kind
  INTO v_fulfill
  FROM public.ingredients AS ingredient
  WHERE ingredient.id = p_ingredient_id
    AND ingredient.tenant_id = v_tenant
    AND ingredient.is_active IS TRUE;

  IF v_fulfill IS NULL THEN
    RAISE EXCEPTION 'ingredient_fulfill_site_required'
      USING ERRCODE = 'check_violation';
  END IF;
  IF p_quantity IS NULL OR p_quantity <= 0 THEN
    RAISE EXCEPTION 'stock_request_qty_invalid' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.stock_request_items (
    tenant_id,
    request_id,
    ingredient_id,
    entry_unit_id,
    quantity,
    fulfill_site_kind,
    status
  )
  VALUES (
    v_tenant,
    p_request_id,
    p_ingredient_id,
    p_entry_unit_id,
    p_quantity,
    v_fulfill,
    'pending'
  )
  RETURNING id INTO v_item_id;

  RETURN jsonb_build_object(
    'item_id', v_item_id,
    'fulfill_site_kind', v_fulfill
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_stock_request(
  p_request_id bigint
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_tenant bigint := public.auth_tenant_id();
  v_req public.stock_requests%ROWTYPE;
  v_line_count int;
BEGIN
  IF auth.uid() IS NULL OR v_tenant IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '28000';
  END IF;

  SELECT * INTO v_req
  FROM public.stock_requests AS req
  WHERE req.id = p_request_id AND req.tenant_id = v_tenant
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'stock_request_not_found' USING ERRCODE = 'no_data_found';
  END IF;
  IF v_req.status IS DISTINCT FROM 'draft' THEN
    RAISE EXCEPTION 'stock_request_not_draft' USING ERRCODE = '22023';
  END IF;
  IF NOT public.auth_is_owner(auth.uid())
     AND NOT public.has_permission(
       v_req.branch_id,
       'inventory:request_submit'
     )
  THEN
    RAISE EXCEPTION 'forbidden_request_submit' USING ERRCODE = '42501';
  END IF;

  SELECT count(*)::int INTO v_line_count
  FROM public.stock_request_items AS item
  WHERE item.request_id = p_request_id
    AND item.tenant_id = v_tenant;

  IF v_line_count < 1 THEN
    RAISE EXCEPTION 'stock_request_empty' USING ERRCODE = '22023';
  END IF;

  UPDATE public.stock_requests
  SET status = 'submitted',
      submitted_at = now(),
      updated_at = now()
  WHERE id = p_request_id;

  RETURN jsonb_build_object('request_id', p_request_id, 'status', 'submitted');
END;
$$;

CREATE OR REPLACE FUNCTION public.cancel_stock_request(
  p_request_id bigint
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_tenant bigint := public.auth_tenant_id();
  v_req public.stock_requests%ROWTYPE;
BEGIN
  IF auth.uid() IS NULL OR v_tenant IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '28000';
  END IF;

  SELECT * INTO v_req
  FROM public.stock_requests AS req
  WHERE req.id = p_request_id AND req.tenant_id = v_tenant
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'stock_request_not_found' USING ERRCODE = 'no_data_found';
  END IF;
  IF v_req.status NOT IN ('draft', 'submitted') THEN
    RAISE EXCEPTION 'stock_request_not_cancellable' USING ERRCODE = '22023';
  END IF;
  IF NOT public.auth_is_owner(auth.uid())
     AND NOT public.has_permission(
       v_req.branch_id,
       'inventory:request_cancel'
     )
  THEN
    RAISE EXCEPTION 'forbidden_request_cancel' USING ERRCODE = '42501';
  END IF;

  UPDATE public.stock_request_items
  SET status = 'cancelled', updated_at = now()
  WHERE request_id = p_request_id
    AND tenant_id = v_tenant
    AND status = 'pending';

  UPDATE public.stock_requests
  SET status = 'cancelled',
      cancelled_at = now(),
      updated_at = now()
  WHERE id = p_request_id;

  RETURN jsonb_build_object('request_id', p_request_id, 'status', 'cancelled');
END;
$$;

CREATE OR REPLACE FUNCTION public.fulfill_stock_request_lines(
  p_request_id bigint,
  p_fulfill_site_kind text,
  p_from_branch_id bigint,
  p_from_location_id bigint,
  p_item_ids bigint[]
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_tenant bigint := public.auth_tenant_id();
  v_req public.stock_requests%ROWTYPE;
  v_from_kind text;
  v_to_location_id bigint;
  v_lines jsonb := '[]'::jsonb;
  v_item public.stock_request_items%ROWTYPE;
  v_result jsonb;
  v_transfer_id bigint;
  v_pending int;
  v_done int;
BEGIN
  IF v_uid IS NULL OR v_tenant IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '28000';
  END IF;

  IF p_fulfill_site_kind IS DISTINCT FROM 'central_supply'
     AND p_fulfill_site_kind IS DISTINCT FROM 'central_kitchen' THEN
    RAISE EXCEPTION 'fulfill_site_kind_invalid' USING ERRCODE = '22023';
  END IF;

  IF NOT public.auth_is_owner(auth.uid())
     AND NOT public.has_permission_any('inventory:request_fulfill')
  THEN
    RAISE EXCEPTION 'forbidden_request_fulfill' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO v_req
  FROM public.stock_requests AS req
  WHERE req.id = p_request_id AND req.tenant_id = v_tenant
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'stock_request_not_found' USING ERRCODE = 'no_data_found';
  END IF;
  IF v_req.status NOT IN ('submitted', 'partially_fulfilled') THEN
    RAISE EXCEPTION 'stock_request_not_fulfillable' USING ERRCODE = '22023';
  END IF;

  SELECT branch.branch_kind INTO v_from_kind
  FROM public.branches AS branch
  WHERE branch.id = p_from_branch_id
    AND branch.tenant_id = v_tenant
    AND branch.is_active IS TRUE;

  IF v_from_kind IS DISTINCT FROM p_fulfill_site_kind THEN
    RAISE EXCEPTION 'fulfill_from_site_mismatch'
      USING ERRCODE = 'check_violation';
  END IF;

  IF NOT public.auth_is_owner(auth.uid())
     AND public.auth_branch_id() IS DISTINCT FROM p_from_branch_id
     AND public.auth_role() IN (
       'central_supply_ops',
       'central_kitchen_lead'
     )
  THEN
    RAISE EXCEPTION 'forbidden_request_fulfill_scope'
      USING ERRCODE = '42501';
  END IF;

  SELECT location.id INTO v_to_location_id
  FROM public.inventory_locations AS location
  WHERE location.tenant_id = v_tenant
    AND location.branch_id = v_req.branch_id
    AND location.location_kind = 'warehouse'
    AND location.is_active IS TRUE
  LIMIT 1;

  IF v_to_location_id IS NULL THEN
    RAISE EXCEPTION 'stock_request_destination_warehouse_missing'
      USING ERRCODE = 'check_violation';
  END IF;

  FOR v_item IN
    SELECT *
    FROM public.stock_request_items AS item
    WHERE item.request_id = p_request_id
      AND item.tenant_id = v_tenant
      AND item.id = ANY (p_item_ids)
      AND item.fulfill_site_kind = p_fulfill_site_kind
      AND item.status = 'pending'
    FOR UPDATE
  LOOP
    v_lines := v_lines || jsonb_build_array(
      jsonb_build_object(
        'ingredient_id', v_item.ingredient_id,
        'entry_unit_id', v_item.entry_unit_id,
        'quantity', v_item.quantity
      )
    );
  END LOOP;

  IF jsonb_array_length(v_lines) = 0 THEN
    RAISE EXCEPTION 'stock_request_fulfill_empty' USING ERRCODE = '22023';
  END IF;

  v_result := public.create_stock_transfer_draft(
    p_from_branch_id,
    v_req.branch_id,
    '',
    'Fulfill stock request ' || v_req.request_number,
    NULL,
    v_lines,
    p_from_location_id,
    v_to_location_id
  );

  v_transfer_id := coalesce(
    (v_result ->> 'id')::bigint,
    (v_result ->> 'transfer_id')::bigint
  );

  UPDATE public.stock_request_items
  SET status = 'allocated',
      transfer_id = v_transfer_id,
      updated_at = now()
  WHERE request_id = p_request_id
    AND tenant_id = v_tenant
    AND id = ANY (p_item_ids)
    AND fulfill_site_kind = p_fulfill_site_kind
    AND status = 'pending';

  SELECT
    count(*) FILTER (WHERE status = 'pending')::int,
    count(*) FILTER (
      WHERE status IN ('allocated', 'shipped', 'received')
    )::int
  INTO v_pending, v_done
  FROM public.stock_request_items
  WHERE request_id = p_request_id
    AND tenant_id = v_tenant
    AND status <> 'cancelled';

  UPDATE public.stock_requests
  SET status = CASE
        WHEN v_pending = 0 THEN 'fulfilled'
        WHEN v_done > 0 THEN 'partially_fulfilled'
        ELSE status
      END,
      updated_at = now()
  WHERE id = p_request_id;

  RETURN jsonb_build_object(
    'request_id', p_request_id,
    'transfer_id', v_transfer_id,
    'transfer_number', v_result ->> 'transfer_number'
  );
END;
$$;

