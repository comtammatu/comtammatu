-- ── 4) stock_requests tables ────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.stock_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL REFERENCES public.tenants(id),
  branch_id bigint NOT NULL REFERENCES public.branches(id),
  request_number text NOT NULL,
  status text NOT NULL DEFAULT 'draft',
  notes text,
  created_by uuid REFERENCES auth.users(id),
  submitted_at timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT stock_requests_status_check CHECK (
    status = ANY (ARRAY[
      'draft'::text,
      'submitted'::text,
      'partially_fulfilled'::text,
      'fulfilled'::text,
      'cancelled'::text
    ])
  ),
  CONSTRAINT stock_requests_tenant_number_unique
    UNIQUE (tenant_id, request_number)
);

CREATE TABLE IF NOT EXISTS public.stock_request_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL REFERENCES public.tenants(id),
  request_id bigint NOT NULL
    REFERENCES public.stock_requests(id) ON DELETE CASCADE,
  ingredient_id bigint NOT NULL REFERENCES public.ingredients(id),
  entry_unit_id bigint NOT NULL REFERENCES public.units(id),
  quantity numeric(15, 3) NOT NULL,
  fulfill_site_kind text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  transfer_id bigint REFERENCES public.stock_transfers(id),
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT stock_request_items_qty_check CHECK (quantity > 0),
  CONSTRAINT stock_request_items_fulfill_kind_check CHECK (
    fulfill_site_kind = ANY (
      ARRAY['central_supply'::text, 'central_kitchen'::text]
    )
  ),
  CONSTRAINT stock_request_items_status_check CHECK (
    status = ANY (ARRAY[
      'pending'::text,
      'allocated'::text,
      'shipped'::text,
      'received'::text,
      'rejected'::text,
      'cancelled'::text
    ])
  )
);

CREATE INDEX IF NOT EXISTS stock_requests_branch_status_idx
  ON public.stock_requests (tenant_id, branch_id, status);

CREATE INDEX IF NOT EXISTS stock_request_items_fulfill_pending_idx
  ON public.stock_request_items (tenant_id, fulfill_site_kind, status)
  WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS stock_request_items_request_idx
  ON public.stock_request_items (request_id);

