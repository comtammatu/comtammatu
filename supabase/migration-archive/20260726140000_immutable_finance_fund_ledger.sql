CREATE OR REPLACE FUNCTION private.guard_legacy_finance_settings()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO ''
AS $$
DECLARE
  v_protected_keys constant text[] := ARRAY[
    'cash_opening_balance',
    'bank_opening_balance',
    'cash_opening_date'
  ];
BEGIN
  IF TG_OP = 'INSERT' AND NEW.key = ANY(v_protected_keys) THEN
    RAISE EXCEPTION 'legacy_finance_setting_locked'
      USING ERRCODE = '55000';
  END IF;

  IF TG_OP = 'UPDATE'
    AND (
      OLD.key = ANY(v_protected_keys)
      OR NEW.key = ANY(v_protected_keys)
    )
  THEN
    RAISE EXCEPTION 'legacy_finance_setting_locked'
      USING ERRCODE = '55000';
  END IF;

  IF TG_OP = 'DELETE' AND OLD.key = ANY(v_protected_keys) THEN
    RAISE EXCEPTION 'legacy_finance_setting_locked'
      USING ERRCODE = '55000';
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER system_settings_guard_legacy_finance_opening
BEFORE INSERT OR UPDATE OR DELETE ON public.system_settings
FOR EACH ROW
EXECUTE FUNCTION private.guard_legacy_finance_settings();

