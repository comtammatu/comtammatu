CREATE TABLE public.finance_fund_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
  entry_type text NOT NULL CHECK (entry_type IN ('opening', 'adjustment')),
  cash_delta numeric(15,2) NOT NULL DEFAULT 0,
  bank_delta numeric(15,2) NOT NULL DEFAULT 0,
  effective_at timestamptz NOT NULL,
  reason text NOT NULL CHECK (
    char_length(btrim(reason)) BETWEEN 5 AND 500
  ),
  created_by uuid NOT NULL REFERENCES public.profiles(id),
  idempotency_key uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  CONSTRAINT finance_fund_entries_amount_range CHECK (
    abs(cash_delta) <= 100000000000
    AND abs(bank_delta) <= 100000000000
  ),
  CONSTRAINT finance_fund_entries_entry_amount CHECK (
    (entry_type = 'opening' AND cash_delta >= 0 AND bank_delta >= 0)
    OR
    (entry_type = 'adjustment' AND (cash_delta <> 0 OR bank_delta <> 0))
  ),
  CONSTRAINT finance_fund_entries_effective_at_check CHECK (
    isfinite(effective_at) AND effective_at <= created_at
  ),
  CONSTRAINT finance_fund_entries_tenant_idempotency_key_key
    UNIQUE (tenant_id, idempotency_key)
);

CREATE UNIQUE INDEX finance_fund_entries_one_opening_per_tenant
  ON public.finance_fund_entries (tenant_id)
  WHERE entry_type = 'opening';

CREATE INDEX finance_fund_entries_tenant_effective_at_idx
  ON public.finance_fund_entries (tenant_id, effective_at, id);

COMMENT ON TABLE public.finance_fund_entries IS
  'Immutable tenant-wide book-fund opening and audited adjustments. Operational movements remain in their canonical ledgers.';

ALTER TABLE public.finance_fund_entries ENABLE ROW LEVEL SECURITY;

CREATE POLICY finance_fund_entries_owner_select
  ON public.finance_fund_entries
  FOR SELECT
  TO authenticated
  USING (
    tenant_id = (SELECT public.auth_tenant_id())
    AND (SELECT public.auth_role()) = 'owner'
  );

REVOKE ALL ON TABLE public.finance_fund_entries
  FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT ON TABLE public.finance_fund_entries TO authenticated;

