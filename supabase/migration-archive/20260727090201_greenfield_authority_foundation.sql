CREATE OR REPLACE FUNCTION private.can_company(
  p_capability text,
  p_company_id bigint
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.companies company
    JOIN private.company_memberships membership
      ON membership.company_id = company.id
    JOIN private.access_bindings binding
      ON binding.company_membership_id = membership.id
     AND binding.auth_user_id = membership.auth_user_id
     AND binding.company_id = membership.company_id
     AND binding.scope_kind = 'company'
    JOIN private.access_roles role
      ON role.id = binding.role_id
     AND role.scope_kind = binding.scope_kind
     AND role.subject_kind = membership.subject_kind
    JOIN private.access_role_capabilities role_capability
      ON role_capability.role_id = role.id
     AND role_capability.role_scope_kind = role.scope_kind
    JOIN private.capabilities capability
      ON capability.key = role_capability.capability_key
    WHERE company.id = p_company_id
      AND company.is_active
      AND membership.auth_user_id = auth.uid()
      AND membership.status = 'active'
      AND membership.valid_from <= now()
      AND (membership.valid_until IS NULL OR membership.valid_until > now())
      AND binding.revoked_at IS NULL
      AND binding.valid_from <= now()
      AND (binding.valid_until IS NULL OR binding.valid_until > now())
      AND role.is_active
      AND capability.key = p_capability
      AND capability.is_active
      AND role_capability.capability_scope_kind = 'company'
      AND (
        capability.required_aal = 'aal1'
        OR auth.jwt() ->> 'aal' = 'aal2'
      )
  );
$$;

