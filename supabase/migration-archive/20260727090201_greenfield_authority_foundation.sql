CREATE OR REPLACE FUNCTION private.guard_lifecycle_update()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF OLD.status <> 'active' THEN
    RAISE EXCEPTION 'closed lifecycle rows are immutable'
      USING ERRCODE = '23514';
  END IF;

  IF NEW.status = 'active' OR NEW.ended_at IS NULL THEN
    RAISE EXCEPTION 'lifecycle rows may only transition out of active'
      USING ERRCODE = '23514';
  END IF;

  IF (to_jsonb(NEW) - ARRAY['status', 'ended_at', 'updated_at'])
     IS DISTINCT FROM
     (to_jsonb(OLD) - ARRAY['status', 'ended_at', 'updated_at']) THEN
    RAISE EXCEPTION 'lifecycle identity and scope are immutable'
      USING ERRCODE = '23514';
  END IF;

  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER company_memberships_guard_update
BEFORE UPDATE ON private.company_memberships
FOR EACH ROW EXECUTE FUNCTION private.guard_lifecycle_update();

