CREATE OR REPLACE FUNCTION private.guard_access_binding_update()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF OLD.revoked_at IS NOT NULL THEN
    RAISE EXCEPTION 'revoked bindings are immutable'
      USING ERRCODE = '23514';
  END IF;

  IF (to_jsonb(NEW) - ARRAY[
        'valid_until',
        'revoked_at',
        'revoked_by',
        'revoke_reason',
        'updated_at'
      ])
     IS DISTINCT FROM
     (to_jsonb(OLD) - ARRAY[
        'valid_until',
        'revoked_at',
        'revoked_by',
        'revoke_reason',
        'updated_at'
      ]) THEN
    RAISE EXCEPTION 'binding identity, role, and scope are immutable'
      USING ERRCODE = '23514';
  END IF;

  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

