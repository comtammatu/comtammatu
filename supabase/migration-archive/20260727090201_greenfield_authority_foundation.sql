  END;
$$;

CREATE OR REPLACE FUNCTION private.validate_access_role_capability()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_role private.access_roles%ROWTYPE;
  v_capability private.capabilities%ROWTYPE;
BEGIN
  SELECT *
  INTO STRICT v_role
  FROM private.access_roles
  WHERE id = NEW.role_id;

  SELECT *
  INTO STRICT v_capability
  FROM private.capabilities
  WHERE key = NEW.capability_key;

  IF v_role.subject_kind <> v_capability.subject_kind
     AND v_capability.subject_kind <> 'both' THEN
    RAISE EXCEPTION 'role subject kind does not match capability subject kind'
      USING ERRCODE = '23514';
  END IF;

  IF v_role.assignment_class = 'machine_only'
     AND v_capability.minimum_assignment_class <> 'machine_only' THEN
    RAISE EXCEPTION 'machine-only roles may contain only machine capabilities'
      USING ERRCODE = '23514';
  END IF;

  IF v_role.assignment_class <> 'machine_only'
     AND v_capability.minimum_assignment_class = 'machine_only' THEN
    RAISE EXCEPTION 'human roles may not contain machine capabilities'
      USING ERRCODE = '23514';
  END IF;

  IF v_role.assignment_class <> 'machine_only'
     AND private.assignment_class_rank(v_role.assignment_class)
       < private.assignment_class_rank(v_capability.minimum_assignment_class) THEN
    RAISE EXCEPTION 'role assignment class is below capability minimum'
      USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER access_role_capabilities_validate
BEFORE INSERT OR UPDATE ON private.access_role_capabilities
FOR EACH ROW EXECUTE FUNCTION private.validate_access_role_capability();

CREATE OR REPLACE FUNCTION private.validate_access_binding()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_role private.access_roles%ROWTYPE;
  v_subject_kind text;
BEGIN
  SELECT *
  INTO STRICT v_role
  FROM private.access_roles
  WHERE id = NEW.role_id
    AND scope_kind = NEW.scope_kind
    AND is_active;

  IF v_role.requires_expiry AND NEW.valid_until IS NULL THEN
    RAISE EXCEPTION 'role binding requires an expiry'
      USING ERRCODE = '23514';
  END IF;

  IF v_role.max_binding_duration IS NOT NULL
     AND (
       NEW.valid_until IS NULL
       OR NEW.valid_until - NEW.valid_from > v_role.max_binding_duration
     ) THEN
    RAISE EXCEPTION 'role binding exceeds maximum duration'
      USING ERRCODE = '23514';
  END IF;

  SELECT subject_kind
  INTO STRICT v_subject_kind
  FROM private.company_memberships
  WHERE auth_user_id = NEW.auth_user_id
    AND company_id = NEW.company_id
    AND (
      id = NEW.company_membership_id
      OR id = (
        SELECT company_membership_id
        FROM private.tenant_memberships
        WHERE id = NEW.tenant_membership_id
      )
      OR id = (
        SELECT tm.company_membership_id
        FROM private.site_assignments sa
        JOIN private.tenant_memberships tm
          ON tm.id = sa.tenant_membership_id
        WHERE sa.id = NEW.site_assignment_id
      )
    );

  IF v_subject_kind <> v_role.subject_kind THEN
    RAISE EXCEPTION 'role subject kind does not match membership subject kind'
      USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

