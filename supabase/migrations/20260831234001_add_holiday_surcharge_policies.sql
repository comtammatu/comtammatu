  v_note_trim text;
  v_amount numeric(15,2);
  v_total_amount numeric(15,2);
  v_has_pending boolean;
BEGIN
  v_uid := auth.uid();
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'unauthenticated' USING ERRCODE = '28000';
  END IF;

  SELECT
    p.tenant_id,
    p.branch_id,
    COALESCE(private.staff_role_from_position_code(po.code), 'unassigned')
  INTO v_prof_tenant, v_prof_branch, v_prof_role
  FROM public.profiles p
  LEFT JOIN public.positions po ON po.id = p.position_id
  WHERE p.id = v_uid;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'profile not found' USING ERRCODE = '28000';
  END IF;

  IF v_prof_role IS NULL OR v_prof_role NOT IN
     ('owner', 'branch_manager', 'cashier') THEN
    RAISE EXCEPTION 'forbidden' USING ERRCODE = '42501';
  END IF;

  IF p_amount IS NULL OR p_amount < 0 THEN
    RAISE EXCEPTION 'service_charge_invalid_amount' USING ERRCODE = '22023';
  END IF;

  IF p_amount > 50000000 THEN
    RAISE EXCEPTION 'service_charge_amount_too_large' USING ERRCODE = '22023';
  END IF;

  v_note_trim := COALESCE(btrim(p_note), '');
  IF length(v_note_trim) < 3 THEN
    RAISE EXCEPTION 'service_charge_note_required' USING ERRCODE = '22023';
  END IF;

  PERFORM pg_advisory_xact_lock(p_order_id);

  SELECT
    o.id,
    o.tenant_id,
    o.branch_id,
    o.status,
    o.payment_status
  INTO v_order
  FROM public.orders o
  WHERE o.id = p_order_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'order not found' USING ERRCODE = 'P0002';
  END IF;

  IF v_order.tenant_id <> v_prof_tenant THEN
    RAISE EXCEPTION 'tenant mismatch' USING ERRCODE = '42501';
  END IF;

  IF v_prof_role = 'owner' THEN
    PERFORM 1
    FROM public.branches b
    WHERE b.id = v_order.branch_id
      AND b.tenant_id = v_prof_tenant;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'invalid branch' USING ERRCODE = 'P0002';
    END IF;
  ELSIF v_prof_branch IS NULL
        OR v_order.branch_id IS DISTINCT FROM v_prof_branch THEN
    RAISE EXCEPTION 'branch mismatch' USING ERRCODE = '42501';
  END IF;

  IF v_order.status IN ('completed', 'cancelled') THEN
    RAISE EXCEPTION 'order terminal' USING ERRCODE = '22023';
  END IF;

  IF COALESCE(v_order.payment_status, 'unpaid') = 'paid' THEN
    RAISE EXCEPTION 'order already paid' USING ERRCODE = '22023';
  END IF;

  SELECT EXISTS (
    SELECT 1
    FROM public.payments p
    WHERE p.order_id = p_order_id
      AND p.tenant_id = v_order.tenant_id
      AND p.branch_id = v_order.branch_id
      AND p.status = 'pending'
  )
  INTO v_has_pending;

  IF COALESCE(v_order.payment_status, 'unpaid') = 'pending'
     OR v_has_pending THEN
    RAISE EXCEPTION 'service_charge_payment_pending'
      USING ERRCODE = '22023';
  END IF;

  v_amount := ROUND(p_amount::numeric, 2);

  UPDATE public.orders
  SET service_charge = v_amount,
      holiday_surcharge_source = CASE
        WHEN v_amount = 0 THEN 'waived'
        ELSE 'manual'
      END,
      updated_at = now()
  WHERE id = p_order_id
  RETURNING total_amount INTO v_total_amount;

  INSERT INTO public.order_status_history (
    tenant_id,
    order_id,
    from_status,
    to_status,
    changed_by,
    note
  ) VALUES (
    v_order.tenant_id,
    p_order_id,
    v_order.status,
    v_order.status,
    v_uid,
    CASE
      WHEN v_amount = 0 THEN 'holiday_surcharge_waived'
      ELSE 'holiday_surcharge_manual: ' || v_amount::text || 'đ'
    END || ' :: ' || v_note_trim
  );

  RETURN jsonb_build_object(
    'order_id', p_order_id,
    'service_charge', v_amount,
    'total_amount', v_total_amount
  );
END;
$$;

COMMENT ON FUNCTION public.set_order_service_charge(bigint, numeric, text) IS
  'Manually override or waive the holiday surcharge before payment while preserving the original automatic policy snapshot.';
