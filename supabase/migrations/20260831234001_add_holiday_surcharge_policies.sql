CREATE OR REPLACE FUNCTION public.pos_normalize_order_discount_totals()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_item_discount numeric(15,2) := 0;
  v_order_discount numeric(15,2) := 0;
  v_discount_base numeric(15,2) := 0;
  v_surcharge_base numeric(15,2) := 0;
  v_policy record;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_item_discount := COALESCE(NEW.item_discount_amount, 0);

    IF NEW.holiday_surcharge_source = 'none'
       AND NEW.holiday_surcharge_policy_id IS NULL THEN
      SELECT
        p.id,
        p.name,
        p.calculation_type,
        p.value
      INTO v_policy
      FROM public.holiday_surcharge_policies p
      WHERE p.tenant_id = NEW.tenant_id
        AND (p.branch_id IS NULL OR p.branch_id = NEW.branch_id)
        AND p.is_active
        AND p.starts_at <= COALESCE(NEW.created_at, now())
        AND p.ends_at > COALESCE(NEW.created_at, now())
      ORDER BY (p.branch_id IS NOT NULL) DESC, p.starts_at DESC, p.id DESC
      LIMIT 1;

      IF FOUND THEN
        NEW.holiday_surcharge_policy_id := v_policy.id;
        NEW.holiday_surcharge_source := 'automatic';
        NEW.holiday_surcharge_calculation_type := v_policy.calculation_type;
        NEW.holiday_surcharge_value := v_policy.value;
        NEW.holiday_surcharge_policy_name := v_policy.name;
      END IF;
    END IF;
  ELSE
    SELECT COALESCE(
      SUM(
        LEAST(
          COALESCE(oi.discount_amount, 0),
          COALESCE(oi.subtotal, 0)
        )
      ),
      0
    )
    INTO v_item_discount
    FROM public.order_items oi
    WHERE oi.order_id = NEW.id
      AND oi.tenant_id = NEW.tenant_id
      AND oi.status <> 'cancelled';

    IF NEW.service_charge IS DISTINCT FROM OLD.service_charge
       AND NEW.holiday_surcharge_source
         IS NOT DISTINCT FROM OLD.holiday_surcharge_source
       AND NEW.holiday_surcharge_source <> 'automatic' THEN
      NEW.holiday_surcharge_source := CASE
        WHEN COALESCE(NEW.service_charge, 0) > 0 THEN 'manual'
        ELSE 'waived'
      END;
    END IF;
  END IF;

  IF NEW.status = 'cancelled' THEN
    NEW.item_discount_amount := 0;
    NEW.order_discount_amount := 0;
    NEW.discount_amount := 0;
    NEW.discount_type := NULL;
    NEW.discount_value := NULL;
    NEW.discount_note := NULL;
    NEW.total_amount := GREATEST(0, COALESCE(NEW.service_charge, 0));
    RETURN NEW;
  END IF;

  v_item_discount := LEAST(
    GREATEST(v_item_discount, 0),
    COALESCE(NEW.subtotal, 0)
  );
  v_discount_base := GREATEST(
    COALESCE(NEW.subtotal, 0) - v_item_discount,
    0
  );

  IF NEW.discount_type IS NOT NULL AND NEW.discount_value IS NOT NULL THEN
    IF NEW.discount_type = 'pct' THEN
      NEW.discount_value := LEAST(
        GREATEST(COALESCE(NEW.discount_value, 0), 0),
        100
      );
    ELSIF NEW.discount_type = 'vnd' THEN
      NEW.discount_value := LEAST(
        GREATEST(COALESCE(NEW.discount_value, 0), 0),
        v_discount_base
      );
    END IF;

    v_order_discount := public.compute_discount_amount(
      NEW.discount_type,
      NEW.discount_value,
      v_discount_base
    );
  END IF;

  IF v_order_discount <= 0 THEN
    NEW.order_discount_amount := 0;
    NEW.discount_type := NULL;
    NEW.discount_value := NULL;
    NEW.discount_note := NULL;
  ELSE
    NEW.order_discount_amount := v_order_discount;
    NEW.discount_note := NULLIF(btrim(COALESCE(NEW.discount_note, '')), '');
  END IF;

  NEW.item_discount_amount := v_item_discount;
  NEW.discount_amount := COALESCE(NEW.order_discount_amount, 0)
    + v_item_discount;
  v_surcharge_base := GREATEST(
    0,
    COALESCE(NEW.subtotal, 0) - COALESCE(NEW.discount_amount, 0)
  );

  IF NEW.holiday_surcharge_source = 'automatic' THEN
    IF NEW.holiday_surcharge_calculation_type = 'percentage' THEN
      NEW.service_charge := ROUND(
        v_surcharge_base * NEW.holiday_surcharge_value / 100,
        0
      );
    ELSE
      NEW.service_charge := ROUND(NEW.holiday_surcharge_value, 0);
    END IF;
  ELSIF NEW.holiday_surcharge_source IN ('none', 'waived') THEN
    NEW.service_charge := 0;
  ELSE
    NEW.service_charge := ROUND(COALESCE(NEW.service_charge, 0), 2);
  END IF;

  NEW.total_amount := GREATEST(
    0,
    v_surcharge_base + COALESCE(NEW.service_charge, 0)
  );

  RETURN NEW;
END;
$$;

