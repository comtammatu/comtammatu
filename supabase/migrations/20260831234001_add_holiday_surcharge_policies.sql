CREATE OR REPLACE FUNCTION private.validate_holiday_surcharge_policy()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_branch_tenant bigint;
  v_has_overlap boolean;
BEGIN
  NEW.name := btrim(NEW.name);
  NEW.updated_at := now();

  IF NEW.branch_id IS NOT NULL THEN
    SELECT b.tenant_id
    INTO v_branch_tenant
    FROM public.branches b
    WHERE b.id = NEW.branch_id;

    IF v_branch_tenant IS NULL OR v_branch_tenant <> NEW.tenant_id THEN
      RAISE EXCEPTION 'holiday_surcharge_branch_invalid'
        USING ERRCODE = '22023';
    END IF;
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended(
      'holiday_surcharge_policy:'
        || NEW.tenant_id::text
        || ':'
        || COALESCE(NEW.branch_id::text, 'tenant'),
      0
    )
  );

  IF NEW.is_active THEN
    SELECT EXISTS (
      SELECT 1
      FROM public.holiday_surcharge_policies p
      WHERE p.tenant_id = NEW.tenant_id
        AND p.branch_id IS NOT DISTINCT FROM NEW.branch_id
        AND p.is_active
        AND p.id IS DISTINCT FROM NEW.id
        AND tstzrange(p.starts_at, p.ends_at, '[)')
          && tstzrange(NEW.starts_at, NEW.ends_at, '[)')
    )
    INTO v_has_overlap;

    IF v_has_overlap THEN
      RAISE EXCEPTION 'holiday_surcharge_policy_overlap'
        USING ERRCODE = '23P01';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_holiday_surcharge_policy
  BEFORE INSERT OR UPDATE OF
