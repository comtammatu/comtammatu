CREATE TABLE public.holiday_surcharge_policies (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL
    REFERENCES public.tenants(id) ON DELETE CASCADE,
  branch_id bigint
    REFERENCES public.branches(id) ON DELETE CASCADE,
  name text NOT NULL,
  calculation_type text NOT NULL,
  value numeric(15,2) NOT NULL,
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_by uuid NOT NULL
    REFERENCES public.profiles(id) ON DELETE RESTRICT,
  updated_by uuid NOT NULL
    REFERENCES public.profiles(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT holiday_surcharge_policies_name_check
    CHECK (length(btrim(name)) BETWEEN 3 AND 120),
  CONSTRAINT holiday_surcharge_policies_calculation_type_check
    CHECK (calculation_type IN ('percentage', 'fixed')),
  CONSTRAINT holiday_surcharge_policies_value_check
    CHECK (
      (
        calculation_type = 'percentage'
        AND value > 0
        AND value <= 100
      )
      OR (
        calculation_type = 'fixed'
        AND value > 0
        AND value <= 50000000
        AND value = trunc(value)
      )
    ),
  CONSTRAINT holiday_surcharge_policies_time_check
    CHECK (ends_at > starts_at)
);

COMMENT ON TABLE public.holiday_surcharge_policies IS
  'Owner-configured holiday surcharge schedules. Branch-specific policies override tenant-wide policies.';
COMMENT ON COLUMN public.holiday_surcharge_policies.value IS
  'Percentage points when calculation_type=percentage, otherwise a fixed VND amount.';
COMMENT ON COLUMN public.holiday_surcharge_policies.ends_at IS
  'Exclusive policy end timestamp.';

