CREATE OR REPLACE FUNCTION public.get_holiday_surcharge_policies()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_tenant bigint := public.auth_tenant_id();
  v_result jsonb;
BEGIN
  IF v_uid IS NULL OR v_tenant IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '28000';
  END IF;

  IF NOT public.auth_is_owner(v_uid)
     OR NOT public.has_permission_any('settings:tenant') THEN
    RAISE EXCEPTION 'forbidden' USING ERRCODE = '42501';
  END IF;

  SELECT COALESCE(
    jsonb_agg(
      jsonb_build_object(
        'id', p.id,
        'branch_id', p.branch_id,
        'branch_name', b.name,
        'name', p.name,
        'calculation_type', p.calculation_type,
        'value', p.value,
        'starts_at', p.starts_at,
        'ends_at', p.ends_at,
        'is_active', p.is_active,
        'created_at', p.created_at,
        'updated_at', p.updated_at
      )
      ORDER BY p.is_active DESC, p.starts_at DESC, p.id DESC
    ),
    '[]'::jsonb
  )
  INTO v_result
  FROM public.holiday_surcharge_policies p
  LEFT JOIN public.branches b
    ON b.id = p.branch_id
   AND b.tenant_id = p.tenant_id
  WHERE p.tenant_id = v_tenant;

  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.upsert_holiday_surcharge_policy(
  p_policy_id bigint,
  p_name text,
  p_branch_id bigint,
  p_calculation_type text,
  p_value numeric,
  p_starts_at timestamptz,
  p_ends_at timestamptz,
  p_is_active boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_tenant bigint := public.auth_tenant_id();
  v_policy public.holiday_surcharge_policies%ROWTYPE;
BEGIN
  IF v_uid IS NULL OR v_tenant IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '28000';
  END IF;

  IF NOT public.auth_is_owner(v_uid)
     OR NOT public.has_permission_any('settings:tenant') THEN
    RAISE EXCEPTION 'forbidden' USING ERRCODE = '42501';
  END IF;

  IF p_name IS NULL
     OR p_calculation_type IS NULL
     OR p_value IS NULL
     OR p_starts_at IS NULL
     OR p_ends_at IS NULL
     OR p_is_active IS NULL THEN
    RAISE EXCEPTION 'holiday_surcharge_policy_invalid'
      USING ERRCODE = '22023';
  END IF;

  IF p_branch_id IS NOT NULL AND NOT EXISTS (
    SELECT 1
    FROM public.branches b
    WHERE b.id = p_branch_id
      AND b.tenant_id = v_tenant
      AND b.is_active IS TRUE
      AND b.branch_kind = 'branch'
  ) THEN
    RAISE EXCEPTION 'holiday_surcharge_branch_invalid'
      USING ERRCODE = '22023';
  END IF;

  IF p_policy_id IS NULL THEN
    INSERT INTO public.holiday_surcharge_policies (
      tenant_id,
      branch_id,
      name,
      calculation_type,
      value,
      starts_at,
      ends_at,
      is_active,
      created_by,
      updated_by
    ) VALUES (
      v_tenant,
      p_branch_id,
      p_name,
      p_calculation_type,
      p_value,
      p_starts_at,
      p_ends_at,
      p_is_active,
      v_uid,
      v_uid
    )
    RETURNING * INTO v_policy;
  ELSE
    UPDATE public.holiday_surcharge_policies p
    SET branch_id = p_branch_id,
        name = p_name,
        calculation_type = p_calculation_type,
        value = p_value,
        starts_at = p_starts_at,
        ends_at = p_ends_at,
        is_active = p_is_active,
        updated_by = v_uid
    WHERE p.id = p_policy_id
      AND p.tenant_id = v_tenant
    RETURNING p.* INTO v_policy;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'holiday_surcharge_policy_not_found'
        USING ERRCODE = 'P0002';
    END IF;
  END IF;

  RETURN jsonb_build_object(
    'id', v_policy.id,
    'is_active', v_policy.is_active,
    'updated_at', v_policy.updated_at
  );
END;
$$;

