-- ---------------------------------------------------------------------------
-- 2. List-price helper (fail loud for missing delivery channel price)
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.pos_resolve_item_list_price(
  p_tenant_id bigint,
  p_menu_item_id bigint,
  p_order_type text,
  p_delivery_platform text DEFAULT NULL
) RETURNS numeric
    LANGUAGE plpgsql
    STABLE
    SET search_path TO ''
AS $$
DECLARE
  v_base numeric(15, 2);
  v_channel numeric(15, 2);
BEGIN
  IF p_order_type = 'delivery' THEN
    IF p_delivery_platform IS NULL
      OR p_delivery_platform NOT IN ('grab', 'shopee', 'be', 'green_sm')
    THEN
      RAISE EXCEPTION 'delivery_platform_required' USING ERRCODE = '22023';
    END IF;

    SELECT cp.unit_price
      INTO v_channel
      FROM public.menu_item_channel_prices cp
     WHERE cp.tenant_id = p_tenant_id
       AND cp.menu_item_id = p_menu_item_id
       AND cp.delivery_platform = p_delivery_platform;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'channel_price_missing: menu_item=% platform=%',
        p_menu_item_id, p_delivery_platform
        USING ERRCODE = 'P0002';
    END IF;

    RETURN v_channel;
  END IF;

  SELECT mi.base_price
    INTO v_base
    FROM public.menu_items mi
   WHERE mi.id = p_menu_item_id
     AND mi.tenant_id = p_tenant_id
     AND mi.is_active = TRUE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Menu item % not found or inactive', p_menu_item_id
      USING ERRCODE = 'P0002';
  END IF;

  RETURN v_base;
END;
$$;

REVOKE ALL ON FUNCTION public.pos_resolve_item_list_price(bigint, bigint, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.pos_resolve_item_list_price(bigint, bigint, text, text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.pos_resolve_item_list_price(bigint, bigint, text, text) TO service_role;

COMMENT ON FUNCTION public.pos_resolve_item_list_price(bigint, bigint, text, text) IS
  'POS list price: menu_items.base_price for dine_in/takeaway; menu_item_channel_prices.unit_price for delivery (no silent fallback).';

-- ---------------------------------------------------------------------------
-- 3. HĐĐT: allow platform tender (same auto-queue path as cash/VietQR)
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION private.sync_tax_invoice_issue_job_for_payment(p_payment_id bigint) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
AS $$
DECLARE
  v_payment public.payments%ROWTYPE;
  v_order public.orders%ROWTYPE;
  v_payload jsonb;
  v_request_payload jsonb;
  v_status text;
BEGIN
  SELECT * INTO v_payment
  FROM public.payments
  WHERE id = p_payment_id
  FOR UPDATE;
  IF NOT FOUND
    OR v_payment.method NOT IN ('vietqr', 'cash', 'platform')
  THEN
    RETURN;
  END IF;

  SELECT * INTO v_order
  FROM public.orders
  WHERE id = v_payment.order_id
    AND tenant_id = v_payment.tenant_id
    AND branch_id = v_payment.branch_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RETURN;
  END IF;

  SELECT request.invoice_payload INTO v_request_payload
  FROM public.self_order_payment_requests request
  WHERE request.tenant_id = v_payment.tenant_id
    AND request.branch_id = v_payment.branch_id
    AND request.order_id = v_payment.order_id
    AND request.payment_id = v_payment.id
    AND request.status IN ('cash_call', 'vietqr_pending', 'completed')
  ORDER BY request.id DESC
  LIMIT 1;

  v_payload := COALESCE(
    v_payment.provider_data -> 'invoiceSnapshot',
    v_payment.provider_data -> 'invoicePayload',
    v_request_payload
  );
  IF v_payload IS NULL THEN
    RETURN;
  END IF;

  IF v_payment.status NOT IN ('pending', 'completed')
    OR (
      v_payment.status = 'completed'
      AND (
        v_order.payment_status <> 'paid'
        OR v_order.status <> 'completed'
      )
    ) THEN
    RETURN;
  END IF;

  v_status := CASE
    WHEN v_payment.status = 'completed' THEN 'queued'
    ELSE 'pending_payment'
  END;

  PERFORM private.upsert_tax_invoice_issue_job(
    v_payment.tenant_id,
    v_payment.branch_id,
    v_payment.order_id,
    v_payment.id,
    v_payload,
    v_status
  );
END;
$$;

-- ---------------------------------------------------------------------------
-- 4. Print header: delivery/GH share Mang về lane label; GH sequence parse
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.print_template_order_header(p_payload jsonb) RETURNS text
    LANGUAGE plpgsql IMMUTABLE
    SET search_path TO 'public'
AS $_$
DECLARE
  v_order_number TEXT := btrim(
    COALESCE(
      NULLIF(p_payload->>'source_order_number', ''),
      NULLIF(p_payload->>'order_number', ''),
      ''
    )
  );
  v_clean_order_number TEXT;
  v_order_type TEXT := COALESCE(p_payload->>'order_type', '');
  v_table_number TEXT := NULLIF(btrim(COALESCE(p_payload->>'table_number', '')), '');
  v_platform TEXT := lower(NULLIF(btrim(COALESCE(p_payload->>'delivery_platform', '')), ''));
  v_external_ref TEXT := NULLIF(btrim(COALESCE(p_payload->>'external_order_ref', '')), '');
  v_prefix TEXT;
  v_label TEXT;
  v_match TEXT[];
  v_sequence TEXT;
  v_is_dine_in BOOLEAN;
  v_platform_label TEXT;
  v_header TEXT;
BEGIN
  v_clean_order_number := regexp_replace(v_order_number, '^#+', '');
  v_prefix := upper(split_part(v_clean_order_number, '-', 1));
  v_is_dine_in := v_order_type = 'dine_in'
    OR (v_order_type NOT IN ('takeaway', 'delivery') AND v_prefix = 'TC');

  v_label := CASE
    WHEN v_is_dine_in AND v_table_number IS NOT NULL THEN 'Bàn ' || v_table_number
    WHEN v_is_dine_in THEN 'Tại bàn'
    WHEN v_order_type IN ('takeaway', 'delivery') OR v_prefix IN ('MV', 'GH') THEN 'Mang về'
    ELSE 'Đơn'
  END;

  v_match := regexp_match(
    v_clean_order_number,
    '^(?:TC|MV|GH)-(?:(?:[0-9]{6}|[0-9]{8})-)?([0-9]{1,4})(?:-.+)?$',
    'i'
  );
  IF v_match IS NOT NULL THEN
    v_sequence := v_match[1];
  END IF;

  IF COALESCE(v_sequence, '') <> '' THEN
    v_header := v_label || ' #' || v_sequence;
  ELSIF v_clean_order_number <> '' THEN
    v_header := v_label || ' ' || v_clean_order_number;
  ELSE
    v_header := v_label;
  END IF;

  IF v_order_type = 'delivery' OR v_prefix = 'GH' THEN
    v_platform_label := CASE v_platform
      WHEN 'grab' THEN 'GRAB'
      WHEN 'shopee' THEN 'SHOPEEFOOD'
      WHEN 'be' THEN 'BEFOOD'
      WHEN 'green_sm' THEN 'GREEN SM'
      ELSE upper(COALESCE(v_platform, 'GIAO HANG'))
    END;
    IF v_external_ref IS NOT NULL THEN
      v_header := v_header || E'\n' || v_platform_label || ' ' || v_external_ref;
    ELSE
      v_header := v_header || E'\n' || v_platform_label;
    END IF;
  END IF;

  RETURN v_header;
END;
$_$;

