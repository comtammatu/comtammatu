CREATE OR REPLACE FUNCTION public.seed_menu_item_channel_prices(
  p_delivery_platform text,
  p_markup_percent numeric DEFAULT NULL,
  p_menu_item_ids bigint[] DEFAULT NULL
) RETURNS jsonb
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_tenant bigint := public.auth_tenant_id();
  v_platform text := lower(btrim(COALESCE(p_delivery_platform, '')));
  v_markup numeric(8, 4);
  v_upserted integer := 0;
BEGIN
  IF v_uid IS NULL OR v_tenant IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '28000';
  END IF;

  IF NOT public.has_permission_any('menu:write') THEN
    RAISE EXCEPTION 'permission denied: menu:write' USING ERRCODE = '42501';
  END IF;

  IF v_platform NOT IN ('grab', 'shopee', 'be', 'green_sm') THEN
    RAISE EXCEPTION 'invalid_delivery_platform' USING ERRCODE = '22023';
  END IF;

  v_markup := COALESCE(
    p_markup_percent,
    CASE WHEN v_platform = 'shopee' THEN 25 ELSE NULL END
  );

  IF v_markup IS NULL OR v_markup < 0 OR v_markup > 500 THEN
    RAISE EXCEPTION 'markup_percent_required' USING ERRCODE = '22023';
  END IF;

  WITH targets AS (
    SELECT mi.id, mi.base_price
    FROM public.menu_items mi
    WHERE mi.tenant_id = v_tenant
      AND mi.is_active = TRUE
      AND (
        p_menu_item_ids IS NULL
        OR mi.id = ANY (p_menu_item_ids)
      )
  ),
  upserted AS (
    INSERT INTO public.menu_item_channel_prices (
      tenant_id, menu_item_id, delivery_platform, unit_price
    )
    SELECT
      v_tenant,
      targets.id,
      v_platform,
      round(targets.base_price * (1 + v_markup / 100.0), 0)
    FROM targets
    ON CONFLICT (tenant_id, menu_item_id, delivery_platform)
    DO UPDATE SET
      unit_price = EXCLUDED.unit_price,
      updated_at = now()
    RETURNING 1
  )
  SELECT count(*)::integer INTO v_upserted FROM upserted;

  RETURN jsonb_build_object(
    'success', true,
    'delivery_platform', v_platform,
    'markup_percent', v_markup,
    'upserted', v_upserted
  );
END;
$$;

