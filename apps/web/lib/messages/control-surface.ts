export function getStaffPermissionLabelVi(
  key: string,
  description: string,
): string {
  return (
    controlSurface.staffPermissions.permissionLabels[key] ??
    (/[À-ỹĐđ]/u.test(description) ? description : UNKNOWN_LABEL_VI)
  );
}
