#!/usr/bin/env node
/**
 * build-design-tokens.mjs
 *
 * Reads `packages/design-tokens/tokens.json` and writes:
 *   - packages/ui/src/styles/matu-tokens.css   (CSS @theme variables for Tailwind v4)
 *
 * Mirrors matu-superapp/scripts/build-design-tokens.mjs (web-only; Flutter
 * generation skipped — comtammatu doesn't ship Flutter yet).
 *
 * Usage:
 *   node scripts/build-design-tokens.mjs           # write outputs
 *   node scripts/build-design-tokens.mjs --check   # exit 1 if outputs would change
 *
 * Tokens are namespaced `matu-*` in CSS so explicit brand-token utilities can
 * coexist with the semantic radix-lyra route API. Route code should prefer
 * `bg-background`, `text-foreground`, and `border-border`; `bg-matu-*` is for
 * token-level implementation and visual QA.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const CHECK = process.argv.includes("--check");

const SOURCE = path.join(REPO_ROOT, "packages/design-tokens/tokens.json");
const WEB_OUT = path.join(REPO_ROOT, "packages/ui/src/styles/matu-tokens.css");

const HEADER_WEB = `/* GENERATED by scripts/build-design-tokens.mjs.\n * Source: packages/design-tokens/tokens.json. Do not hand-edit.\n *\n * Tokens are namespaced \`matu-*\` for explicit brand-token utilities.\n * Route code should prefer semantic classes such as bg-background,\n * text-foreground, and border-border unless implementing or QA-ing tokens. */\n`;

function camelToKebab(s) {
  return s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

function buildWebCss(tokens) {
  const lines = [];
  lines.push(HEADER_WEB);
  lines.push("@theme {");
  for (const [name, def] of Object.entries(tokens.color || {})) {
    lines.push(`  --color-matu-${camelToKebab(name)}: ${def.$value};`);
  }
  for (const [name, def] of Object.entries(tokens.radius || {})) {
    lines.push(`  --radius-matu-${name}: ${def.$value};`);
  }
  for (const [name, def] of Object.entries(tokens.spacing || {})) {
    lines.push(`  --spacing-matu-${name}: ${def.$value};`);
  }
  for (const [name, def] of Object.entries(tokens.shadow || {})) {
    lines.push(`  --shadow-matu-${camelToKebab(name)}: ${def.$value};`);
  }
  for (const [name, def] of Object.entries(tokens.touchTarget || {})) {
    lines.push(`  --touch-target-matu-${camelToKebab(name)}: ${def.$value};`);
  }
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

function main() {
  let tokens;
  try {
    tokens = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
  } catch (err) {
    console.error(`build-design-tokens: failed to read ${SOURCE}`);
    console.error(err.message);
    process.exit(2);
  }

  const webCss = buildWebCss(tokens);

  if (CHECK) {
    const webCurrent = fs.existsSync(WEB_OUT)
      ? fs.readFileSync(WEB_OUT, "utf8")
      : "";
    if (webCurrent !== webCss) {
      console.error(
        "build-design-tokens: drift detected. Run `pnpm tokens:build` and commit.",
      );
      console.error(` - ${path.relative(REPO_ROOT, WEB_OUT)}`);
      process.exit(1);
    }
    console.log("build-design-tokens: clean (no drift).");
    process.exit(0);
  }

  fs.mkdirSync(path.dirname(WEB_OUT), { recursive: true });
  fs.writeFileSync(WEB_OUT, webCss);
  console.log(
    `build-design-tokens: wrote ${path.relative(REPO_ROOT, WEB_OUT)}`,
  );
}

main();
